#!/usr/bin/env python3
"""Dixit mark: a bold geometric D (Montserrat Bold proportions) whose bottom-left corner runs out
into a speech-bubble tail. The letter is the bubble: Dixit writes down who said what.

App icon: the white mark on the diagonal green-to-blue gradient (green top left, blue bottom right),
in the macOS squircle. Python stdlib only.

From `frontend/`:
    python3 src-tauri/icons/source/dixit-mark.py          # dixit.svg, tray-template.svg; UI path on stdout
    python3 src-tauri/icons/source/dixit-mark.py --build  # also every raster: needs rsvg-convert, iconutil, pnpm

The 16/32 px variant (bigger mark, edges on the pixel grid, no shadows) exists only during --build.
The UI mark (src/components/dixit/DixitMark.tsx) pastes the path printed on stdout.
"""
import math
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ICONS = HERE.parent                     # src-tauri/icons
FRONTEND = ICONS.parent.parent          # frontend/

# Brand scale from green to blue.
SCALE = ['#8DC928', '#7EC44E', '#5BBE77', '#25B7AB', '#27A6C2', '#239CCE', '#2099D8']


def num(v):
    return f'{v:.2f}'.rstrip('0').rstrip('.')


def mark(x0, yT, H, S=0.23, A=0.19, B=0.234, W=1.0, R=0.55, k=0.6, tail=(0.40, 0.22)):
    """Path of the mark (fill-rule evenodd): cap height H, stem's left edge at x0, top at yT.
    Fractions of H, defaults measured on Montserrat Bold's D: S stem, A arms, B bowl at its thickest,
    W width, R the bowl's horizontal radius, k its fullness (0.55 = ellipse). tail = how far it runs
    along the baseline and how far below it."""
    S, A, B, W, R = S * H, A * H, B * H, W * H, R * H
    yB, cy, xR = yT + H, yT + H / 2, x0 + W
    r, xa = H / 2, xR - R       # outer bowl; the counter shares its centre
    ri, Ri, xi, x1 = r - A, R - B, xR - B, x0 + S
    p = lambda *v: ' '.join(num(c) for c in v)
    return (f'M{p(x0, yT)}H{num(xa)}C{p(xa + k * R, yT, xR, cy - k * r, xR, cy)}'
            f'C{p(xR, cy + k * r, xa + k * R, yB, xa, yB)}H{num(x0 + tail[0] * H)}L{p(x0, yB + tail[1] * H)}Z'
            f'M{p(x1, yT + A)}H{num(xa)}C{p(xa + k * Ri, yT + A, xi, cy - k * ri, xi, cy)}'
            f'C{p(xi, cy + k * ri, xa + k * Ri, yB - A, xa, yB - A)}H{num(x1)}Z')


def squircle(c=512, r=412, n=5.0, steps=720):
    """macOS icon body: superellipse, 824 wide on the 1024 canvas."""
    pts = []
    for i in range(steps):
        a = 2 * math.pi * i / steps
        x, y = math.cos(a), math.sin(a)
        pts.append((c + r * math.copysign(abs(x) ** (2 / n), x), c + r * math.copysign(abs(y) ** (2 / n), y)))
    return 'M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in pts) + 'Z'


def icon_svg(d, small=False):
    stops = ''.join(f'<stop offset="{num(i / (len(SCALE) - 1))}" stop-color="{c}"/>' for i, c in enumerate(SCALE))
    body = squircle()
    shadow, lift = ('', '') if small else (' filter="url(#shadow)"', ' filter="url(#lift)"')
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <!-- Dixit app icon{' for 16/32 px' if small else ''}, generated by dixit-mark.py: white D-shaped speech
       bubble on the green-to-blue gradient. macOS grid: 824 superellipse body, transparent margins. -->
  <defs>
    <linearGradient id="brand" x1="0" y1="0" x2="1" y2="1">{stops}</linearGradient>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="125%">
      <feDropShadow dx="0" dy="10" stdDeviation="10" flood-color="#000000" flood-opacity="0.28"/>
    </filter>
    <filter id="lift" x="-20%" y="-20%" width="140%" height="140%">
      <feDropShadow dx="0" dy="8" stdDeviation="12" flood-color="#0b3a4a" flood-opacity="0.22"/>
    </filter>
  </defs>
  <path d="{body}" fill="url(#brand)"{shadow}/>
  <path d="{d}" fill="#ffffff" fill-rule="evenodd"{lift}/>
</svg>
'''


def tray_svg():
    """18 pt @2x: stem, arms and top on whole pixels; lighter than the icon, like the system glyphs."""
    d = mark(6, 3, 24, S=4 / 24, A=4 / 24, B=4.5 / 24)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 36 36" width="36" height="36">
  <!-- macOS menu-bar template (18 pt @2x): black + alpha only, the system tints it. Generated by dixit-mark.py. -->
  <path fill="#000000" fill-rule="evenodd" d="{d}"/>
</svg>
'''


MAIN = mark(305, 266, 440)          # cap height 440 on the 824 body, nudged right and up for the tail
SMALL = mark(256, 256, 512, S=0.25, A=0.25, B=0.25)   # 8 px cap at 16 px; stem, arms, bowl on whole pixels at 16 and 32
UI = mark(11, 1.2, 80)              # DixitMark.tsx, viewBox 0 0 100 100

# ---------- rasters ----------

def run(*cmd, cwd=None):
    subprocess.run(cmd, check=True, cwd=cwd)


def svg_png(svg, size, out):
    run('rsvg-convert', '-w', str(size), '-h', str(size), str(svg), '-o', str(out))


def write_ico(pngs, out):
    """ICO with PNG-compressed entries (Vista+), stdlib only."""
    blobs = [(s, Path(p).read_bytes()) for s, p in pngs]
    head = struct.pack('<HHH', 0, 1, len(blobs))
    offset = 6 + 16 * len(blobs)
    entries, data = b'', b''
    for s, b in blobs:
        entries += struct.pack('<BBBBHHII', s % 256, s % 256, 0, 0, 1, 32, len(b), offset + len(data))
        data += b
    Path(out).write_bytes(head + entries + data)


def build():
    main, tray = HERE / 'dixit.svg', HERE / 'tray-template.svg'
    svg_png(tray, 36, ICONS / 'tray-template.png')  # tray-icon draws it at 18 pt: 36 px @2x stays pixel-sharp
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        small = tmp / 'dixit-small.svg'
        small.write_text(icon_svg(SMALL, small=True))

        def png(src, size):
            out = tmp / f'{src.stem}-{size}.png'
            svg_png(src, size, out)
            return out

        master = png(main, 1024)
        # Tauri's own set (Windows/Linux/Store sizes); only the files this repo already ships.
        run('pnpm', 'exec', 'tauri', 'icon', str(master), '-o', str(tmp / 'tauri'), cwd=FRONTEND)
        for f in (tmp / 'tauri').iterdir():
            if f.is_file() and (ICONS / f.name).exists():
                shutil.copy2(f, ICONS / f.name)
        shutil.copy2(png(small, 32), ICONS / '32x32.png')
        # macOS .icns with the small variant at 16 and 32, also kept as loose iconset files.
        iconset = tmp / 'dixit.iconset'
        iconset.mkdir()
        for name, size, src in [('16x16', 16, small), ('16x16@2x', 32, small), ('32x32', 32, small),
                                ('32x32@2x', 64, main), ('128x128', 128, main), ('128x128@2x', 256, main),
                                ('256x256', 256, main), ('256x256@2x', 512, main), ('512x512', 512, main),
                                ('512x512@2x', 1024, main)]:
            shutil.copy2(png(src, size), iconset / f'icon_{name}.png')
            shutil.copy2(iconset / f'icon_{name}.png', ICONS / f'icon_{name}.png')
        run('iconutil', '-c', 'icns', str(iconset), '-o', str(ICONS / 'icon.icns'))
        shutil.copy2(ICONS / 'icon.icns', ICONS / 'app_icon.icns')
        sizes = [(16, small), (24, small), (32, small), (48, main), (64, main), (256, main)]
        write_ico([(s, png(src, s)) for s, src in sizes], ICONS / 'icon.ico')
        shutil.copy2(ICONS / 'icon.ico', ICONS / 'app_icon.ico')
        write_ico([(s, png(src, s)) for s, src in sizes if s in (16, 32, 48, 64)],
                  FRONTEND / 'src' / 'app' / 'favicon.ico')


def main():
    (HERE / 'dixit.svg').write_text(icon_svg(MAIN))
    (HERE / 'tray-template.svg').write_text(tray_svg())
    print(f'UI mark (viewBox 0 0 100 100):\n{UI}')
    if '--build' in sys.argv:
        build()


if __name__ == '__main__':
    main()
